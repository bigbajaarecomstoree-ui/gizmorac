const norm = (s: string) =>
  (s ?? "")
    .toLowerCase()
    .replace(/\band\b/g, "&")
    .replace(/[^a-z]/g, "");

const BY_NORM = new Map(INDIA_STATES.map((s) => [norm(s.name), s]));

/** Best-effort match of a free-text state name to its GST state code (or ""). */
export function gstStateCode(name?: string): string {
  if (!name) return "";
  return BY_NORM.get(norm(name))?.code ?? "";
}

/** Normalised equality check between two state names (seller vs buyer). */
export function sameState(a?: string, b?: string): boolean {
  return Boolean(a && b && norm(a) === norm(b));
}
